#!/usr/bin/env python3
"""Regenerate catalog.js (the SemiBooks shelf on the home page).

Usage: python3 tools/sync-catalog.py [path/to/books/data/books.json]
Default source: migration/books.json. An external portal catalog is optional.
InfraBook metadata stays separate from the imported repository snapshots.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "migration" / "books.json"

# 서가 순서와 semi.euiyun.com/{slug}/ 경로
ORDER = [
    ("devicebook", "device"), ("digitalbook", "digital"), ("designbook", "design"), ("socbook", "soc"),
    ("analogbook", "analog"), ("processbook", "process"), ("lithobook", "litho"), ("etchbook", "etch"),
    ("dopingbook", "doping"), ("yieldbook", "yield"), ("failurebook", "failure"), ("tcadbook", "tcad"),
    ("infrabook", "infra"),
    ("packagingbook", "packaging"), ("testbook", "test"), ("memorybook", "memory"), ("opticsbook", "optics"),
    ("sensorbook", "sensor"), ("displaybook", "display"), ("chipindustrybook", "industry"),
]

# 이 저장소 안에 있는 책 (포털 목록에 아직 없거나, 이 저장소가 원본인 책)
LOCAL = {
    "infrabook": {
        "id": "infrabook", "code": "INF", "title": "InfraBook", "subtitle": "반도체 인프라 교과서",
        "headline": "팹을 움직이는 보이지 않는 공장",
        "description": "클린룸과 공조, 초순수, 가스·케미컬 공급, 배기·스크러버, 폐수와 물 재이용, 전력과 전력 품질, 냉동·냉각수, 진동, 물류 자동화, 가스 안전, 운영 신뢰성, 에너지·탄소, 팹 건설까지. 가상 기준 팹 FAB-E의 숫자로 직접 계산하며 배우는 반도체 인프라 교과서.",
        "url": "infra/", "stage": "infra", "status": "writing", "chapters": 18,
        "color": "#2f5f96", "colorDark": "#8db8ea",
        "topics": ["클린룸·공조", "초순수·폐수", "가스·케미컬", "배기·스크러버", "전력 품질", "냉동·냉각수", "진동·AMHS", "안전·신뢰성·탄소"],
        "motif": "fab",
    },
}

KEYS = ["id", "code", "title", "subtitle", "headline", "description", "url", "stage", "status", "chapters", "simulators", "color", "colorDark", "topics", "motif", "legacyUrl"]


def main():
    portal = {b["id"]: b for b in json.loads(SOURCE.read_text(encoding="utf-8"))["books"]}
    shelf = []
    for book_id, slug in ORDER:
        src = LOCAL.get(book_id) or portal.get(book_id)
        if not src:
            print(f"skip: {book_id} not found", file=sys.stderr)
            continue
        entry = {k: src.get(k) for k in KEYS if src.get(k) is not None}
        entry["slug"] = slug
        entry["local"] = (ROOT / slug / "index.html").exists()
        if entry["local"]:
            entry["url"] = slug + "/"
            entry["chapters"] = len(list((ROOT / slug / "chapters").glob("*.html")))
        if book_id not in LOCAL:
            entry["legacyUrl"] = src.get("legacyUrl") or src.get("url")
        entry.setdefault("motif", "layers")
        shelf.append(entry)
    body = json.dumps(shelf, ensure_ascii=False, indent=1)
    out = ROOT / "catalog.js"
    out.write_text(
        "/* Generated by tools/sync-catalog.py from migration/books.json. Do not edit by hand.\n"
        "   Text: CC-BY-4.0 (see LICENSE.md). */\n"
        f"window.SEMI_BOOKS = {body};\n",
        encoding="utf-8",
    )
    print(f"wrote {out.relative_to(ROOT)} ({len(shelf)} books)")


if __name__ == "__main__":
    main()
