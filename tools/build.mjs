/* Static monorepo build. Directory home canonicals use /memory/, rather than /memory/index.html. */
import { execFileSync } from 'node:child_process';
import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderMath, version as katexVersion } from './katex.mjs';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = join(root, '.book-dist');
const book = JSON.parse(await readFile(join(root, 'book.json'), 'utf8'));
const domain = (await readFile(join(root, 'CNAME'), 'utf8')).trim();
if (book.domain !== domain) throw new Error('CNAME and book.json domain disagree');
const origin = `https://${domain}`;
const excluded = new Set(['.git', '.github', '.book-dist', 'node_modules', 'tools', 'scripts', 'migration', 'package.json', 'package-lock.json', 'pnpm-lock.yaml', '.DS_Store']);

// Books written in this repository declare `meta` in their book.json. Their sources carry only <title> and
// description; canonical, Open Graph and JSON-LD are generated here, and their math is rendered to KaTeX HTML
// so the pages need only the KaTeX stylesheet. Imported books keep their own tags so
// that tools/import-books.py can still sync them byte for byte.
const generated = new Map();
for (const entry of book.books) {
  const slug = dirname(entry);
  const { meta } = JSON.parse(await readFile(join(root, entry), 'utf8'));
  if (!meta) continue;
  const js = await readFile(join(root, slug, 'js/common.js'), 'utf8');
  const chapters = [...js.matchAll(/\{ slug: "([^"]+)",\s*num: "[^"]*",\s*title: "([^"]+)"/g)].map(([, slug, title]) => ({ slug, title }));
  if (!chapters.length) throw new Error(`${slug}: no CHAPTERS in js/common.js`);
  const home = await readFile(join(root, slug, 'index.html'), 'utf8');
  // A book that ships og.png (1200×630) gets it as the share image on every page.
  const image = existsSync(join(root, slug, 'og.png')) ? `${origin}/${slug}/og.png` : undefined;
  generated.set(slug, { ...meta, slug, chapters, image, title: decode(home.match(/<title>([^<]+)<\/title>/)[1]) });
}
const RESOURCE_TYPE = { glossary: '용어집, 퀴즈' };
const katexCss = `<link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/katex@${katexVersion}/dist/katex.min.css">\n`;
const mathErrors = [];

function decode(text) {
  return text.replace(/&(amp|lt|gt|quot|#39);/g, (_, name) => ({ amp: '&', lt: '<', gt: '>', quot: '"', '#39': "'" })[name]);
}
function lastCommitDate(path) {
  try { return execFileSync('git', ['log', '-1', '--format=%cs', '--', path], { cwd: root, encoding: 'utf8' }).trim() || today(); }
  catch { return today(); }
}
function today() { return new Date().toISOString().slice(0, 10); }

function metadata(rel, html, info, url) {
  const title = html.match(/<title>([^<]+)<\/title>/)?.[1];
  const description = html.match(/<meta name="description" content="([^"]+)">/)?.[1];
  if (!title || !description) throw new Error(`${rel}: generated metadata needs <title> and <meta name="description">`);
  const stale = html.match(/<link\b[^>]*rel=["']canonical["']|<meta\b[^>]*(?:property=["']og:|name=["'](?:twitter:|theme-color))|application\/ld\+json/i);
  if (stale) throw new Error(`${rel}: remove "${stale[0]}" — ${info.slug}/ metadata is generated by the build`);
  const bookUrl = `${origin}/${info.slug}/`;
  const isHome = rel === `${info.slug}/index.html`;
  const chapterSlug = rel.match(/\/chapters\/([^/]+)\.html$/)?.[1];
  const position = info.chapters.findIndex((c) => c.slug === chapterSlug) + 1;
  if (!isHome && !position) throw new Error(`${rel}: not a book home or a chapter registered in CHAPTERS`);
  const common = { inLanguage: 'ko', isAccessibleForFree: true, image: info.image };
  const node = isHome
    ? { '@type': 'Book', '@id': `${bookUrl}#book`, name: info.title, alternateName: info.alternateName, url: bookUrl, ...common,
        educationalLevel: info.educationalLevel, about: info.about, description: info.summary, dateModified: lastCommitDate(info.slug),
        isPartOf: { '@type': 'WebSite', '@id': `${origin}/#site`, name: book.title, url: `${origin}/` },
        hasPart: info.chapters.map((c, i) => ({ '@type': 'Chapter', name: c.title, position: i + 1, url: `${bookUrl}chapters/${c.slug}.html` })) }
    : { '@type': ['Chapter', 'LearningResource'], '@id': `${url}#chapter`, name: info.chapters[position - 1].title, headline: decode(title),
        description: decode(description), url, position, ...common, learningResourceType: RESOURCE_TYPE[chapterSlug] || '인터랙티브 교재',
        educationalLevel: info.educationalLevel, dateModified: lastCommitDate(rel),
        isPartOf: { '@type': 'Book', '@id': `${bookUrl}#book`, name: info.title, url: bookUrl } };
  const crumbs = isHome ? [] : [{ '@type': 'BreadcrumbList', itemListElement: [
    { '@type': 'ListItem', position: 1, name: info.siteName, item: bookUrl },
    { '@type': 'ListItem', position: 2, name: info.chapters[position - 1].title, item: url }] }];
  const json = JSON.stringify({ '@context': 'https://schema.org', '@graph': [node, ...crumbs] }).replace(/</g, '\\u003c');
  return [
    `<link rel="canonical" href="${url}">`,
    `<meta name="theme-color" content="${info.themeColor}">`,
    `<meta property="og:type" content="${isHome ? 'website' : 'article'}">`,
    `<meta property="og:site_name" content="${info.siteName}">`,
    '<meta property="og:locale" content="ko_KR">',
    `<meta property="og:title" content="${title}">`,
    `<meta property="og:description" content="${description}">`,
    `<meta property="og:url" content="${url}">`,
    ...(info.image ? [`<meta property="og:image" content="${info.image}">`, '<meta property="og:image:width" content="1200">', '<meta property="og:image:height" content="630">'] : []),
    '<meta name="twitter:card" content="summary_large_image">',
    `<script type="application/ld+json">${json}</script>`,
  ].join('\n') + '\n';
}

await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
for (const item of await readdir(root, { withFileTypes: true })) {
  if (excluded.has(item.name) || item.name.startsWith('.')) continue;
  await cp(join(root, item.name), join(output, item.name), { recursive: true,
    filter: (source) => !relative(root, source).split(sep).some((part) => excluded.has(part)) });
}
const beacon = /<script\b(?=[^>]*\bsrc\s*=\s*["']https:\/\/static\.cloudflareinsights\.com\/beacon\.min\.js["'])[^>]*>\s*<\/script>\s*/gi;
const tag = '<script defer src="https://static.cloudflareinsights.com/beacon.min.js" data-cf-beacon=\'{"token":"3d6151a0abc94ede89285d462527fa80"}\'></script>';
const urls = [];
async function pages(directory) {
  for (const item of await readdir(directory, { withFileTypes: true })) {
    const file = join(directory, item.name);
    if (item.isDirectory()) { await pages(file); continue; }
    if (!item.name.endsWith('.html')) continue;
    const rel = relative(output, file).split(sep).join('/');
    const url = `${origin}/${rel.replace(/(^|\/)index\.html$/, '$1')}`;
    let html = (await readFile(file, 'utf8')).replace(beacon, '');
    if (!/<\/head>/i.test(html)) throw new Error(`Missing </head>: ${rel}`);
    const info = generated.get(rel.split('/')[0]);
    if (info) {
      // Generated tags go right after the description so the head reads in the usual order.
      const description = /(<meta name="description" content="[^"]+">\n)/;
      if (!description.test(html)) throw new Error(`${rel}: <meta name="description"> must sit on its own line`);
      if (/cdn\.jsdelivr\.net\/npm\/katex@/.test(html)) throw new Error(`${rel}: remove the KaTeX tags — the build renders ${info.slug}/ math`);
      const math = renderMath(html, rel);
      mathErrors.push(...math.errors);
      html = math.html.replace(description, `$1${metadata(rel, html, info, url)}${math.count ? katexCss : ''}`);
    } else {
      const existing = html.match(/<link\b[^>]*rel=["']canonical["'][^>]*href=["']([^"']+)/i)?.[1];
      if (existing && existing !== url) throw new Error(`Wrong canonical in ${rel}: ${existing} (expected ${url})`);
      if (!existing) html = html.replace(/<\/head>/i, `<link rel="canonical" href="${url}">\n</head>`);
    }
    html = html.replace(/<\/head>/i, tag + '\n</head>');
    await writeFile(file, html);
    urls.push(url);
  }
}
await pages(output);
if (mathErrors.length) throw new Error(`KaTeX could not parse ${mathErrors.length} formula(s):\n${mathErrors.join('\n')}`);
await writeFile(join(output, 'sitemap.xml'), '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
  urls.sort().map((url) => `  <url><loc>${url}</loc></url>`).join('\n') + '\n</urlset>\n');
await writeFile(join(output, 'robots.txt'), `User-agent: *\nAllow: /\nSitemap: ${origin}/sitemap.xml\n`);
await writeFile(join(output, '.nojekyll'), '');
console.log(`Built ${urls.length} pages across ${book.books.length} books for ${domain}`);
