"""tools/glossary/<slug>.json → 시리즈 공통 용어 데이터와 종합 퀴즈 생성.
JSON: {"terms":[{"ko","en","abbr","def"}], "bank":[{"q","opts":[4],"ans":0..3,"exp"}]}
실행: python3 tools/glossary.py [--check]
"""
import json, re, pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent
CHECK = "--check" in sys.argv
src = (ROOT / "js/common.js").read_text(encoding="utf-8")
order = re.findall(r'slug: "([\w-]+)"', src)
terms, quiz = [], []
for slug in order:
    p = ROOT / "tools/glossary" / f"{slug}.json"
    if not p.exists():
        continue
    d = json.loads(p.read_text(encoding="utf-8"))
    for t in d.get("terms", []):
        assert t["ko"].strip() and t["def"].strip(), (slug, t)
        terms.append({"ko": t["ko"], "en": t.get("en", ""), "abbr": t.get("abbr", ""), "def": t["def"], "chapters": [slug]})
    for q in d.get("bank", []):
        assert len(q["opts"]) >= 2 and 0 <= q["ans"] < len(q["opts"]), (slug, q["q"])
        quiz.append({"ch": slug, "q": q["q"], "o": q["opts"], "a": q["ans"], "e": q["exp"]})
dump = lambda rows: "[\n" + "".join("    " + json.dumps(r, ensure_ascii=False) + ",\n" for r in rows) + "  ]"
g = ROOT / "chapters/glossary.html"
s = g.read_text(encoding="utf-8")
new = ('/*DATA:start*/\n'
       '  var TERMS = window.BOOK_GLOSSARY.terms.map(function (t) {\n'
       '    return { ko: t.ko, en: t.en, abbr: t.abbr, def: t.def, ch: t.chapters[0] };\n'
       '  });\n'
       f'  var QUIZ = {dump(quiz)};\n  /*DATA:end*/')
assert len(re.findall(r"/\*DATA:start\*/.*?/\*DATA:end\*/", s, re.S)) == 1, "용어집 데이터 구역이 하나여야 합니다"
s = re.sub(r"/\*DATA:start\*/.*?/\*DATA:end\*/", lambda m: new, s, flags=re.S)
data = ('/* Copyright (c) 2026 geniuskey and DigitalBook contributors.\n'
        '   Code: MIT. Definitions: CC-BY-4.0 (see ../LICENSE.md). */\n'
        '/* Generated by tools/glossary.py from tools/glossary/*.json.\n'
        '   Series glossary schema v1; shared by the glossary page and prose tooltips. */\n'
        'window.BOOK_GLOSSARY = {\n  version: 1,\n  terms: ' + dump(terms) + '\n};\n')
changed = []
for path, text in ((g, s), (ROOT / "js/glossary-data.js", data)):
    if not path.exists() or path.read_text(encoding="utf-8") != text:
        changed.append(str(path.relative_to(ROOT)))
        if not CHECK:
            path.write_text(text, encoding="utf-8")
print(f"terms {len(terms)}, quiz {len(quiz)}")
if CHECK and changed:
    print("생성 파일을 갱신하세요: python3 tools/glossary.py — " + ", ".join(changed))
    sys.exit(1)
